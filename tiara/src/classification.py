import gzip
import logging
from contextlib import suppress
from typing import Dict, List, Union

import torch
from Bio.SeqIO.FastaIO import SimpleFastaParser
from joblib import Parallel, delayed
from skorch import NeuralNetClassifier

from tiara.src.models import NNet1, NNet2
from tiara.src.prediction import Prediction, SingleResult
from tiara.src.transformations import TfidfWeighter, Transformer
from tiara.src.utilities import chop, parse_params, time_context_manager

logger = logging.getLogger(__name__)


def transform_chopped_sequence(seq, layer, transformer, fragment_len):
    chopped = chop(seq, fragment_len)
    return transformer.transform(chopped)


allowed_letters = set("ACGT")


class Classification:
    """Class that performs classification given neural net and tf-idf models provided.

    Methods
    -------
        classify: classifies an entire fasta file
    """

    def __init__(
        self,
        min_len: int,
        nnet_weights: List[str],
        params: List[Union[Dict[str, int], str]],
        tfidf: List[str],
        threads: int = 1,
        models=(NNet1, NNet2),
    ):
        """Init method.

        Parameters
        ----------
            min_len: minimal length of the sequence to classify
            nnet_weights: a list of paths to nnet weights (generated by skorch for the nnet provided)
            params: either a list of dicts containing neural net params such as number of nodes in hidden layers
                and other parameters such as fragment lenth, kmer length etc,
                or a list of filepaths to .csv files containing parameters
                refer to utilities.parse_params docstring for a specific example
            tfidf: a list of filepaths to tf-idf model
            models: an iterable of torch model classes describing model used
        """
        self.threads = threads
        self.params = [parse_params(param) if isinstance(param, str) else param for param in params]
        self.nnets = self.get_list_of_nnets(models, nnet_weights)
        self.transformers = [TfidfWeighter.load_params(tfidf_param_folder) for tfidf_param_folder in tfidf]
        self.min_len = min_len
        self.layers = len(nnet_weights)
        self.predictors = self.get_list_of_predictions()

    def get_list_of_nnets(
        self,
        models,
        nnet_weights,
    ) -> List[NeuralNetClassifier]:
        data = []
        for model, nnet_weight, params_dict in zip(models, nnet_weights, self.params):
            params_filtered = {
                key: value
                for key, value in params_dict.items()
                if key not in ["k", "fragment_len", "prob_cutoff", "fname"]
            }
            params_filtered.update({"dim_in": 4 ** params_dict["k"]})
            module = model(**params_filtered)
            net = NeuralNetClassifier(module, lr=0.0001, criterion=torch.nn.NLLLoss)
            net.initialize()
            net.load_params(f_params=nnet_weight)
            data.append(net)
        return data

    def get_list_of_predictions(
        self,
    ) -> List[Prediction]:
        return [
            Prediction(
                prob_cutoff=self.params[layer]["prob_cutoff"],
                layer=layer,
                nnet=self.nnets[layer],
                fragment_len=self.params[layer]["fragment_len"],
                k=self.params[layer]["k"],
                tnf=self.transformers[layer],
                transformer=Transformer(
                    fragment_len=self.params[layer]["fragment_len"],
                    k=self.params[layer]["k"],
                    model=self.transformers[layer],
                ),
            )
            for layer in range(self.layers)
        ]

    def classify(self, sequences_fname: str, verbose=False) -> List[SingleResult]:
        """Perform a two-step classification.

        Parameters
        ----------
            sequences_fname : a path to fasta file to classify

        Returns
        -------
            predictions: a list of lists containing SingleResult objects.
        """

        if sequences_fname.endswith(".gz"):
            handler = gzip.open
            mode = "rt"  # Read Text mode for gzipped data
        else:
            handler = open
            mode = "r"

        with handler(sequences_fname, mode) as sequences_handle:
            seqlist = list(SimpleFastaParser(sequences_handle))

        seqs = [x for x in seqlist if len(x[1]) >= self.min_len]

        transformed_sequences = delayed(transform_chopped_sequence)
        executor = Parallel(n_jobs=self.threads)
        tasks = (
            transformed_sequences(x[1], 0, self.predictors[0].transformer, self.params[0]["fragment_len"]) for x in seqs
        )
        cont_manager = time_context_manager("First Stage Classification: Calculating sequence representations")
        with cont_manager:
            seqs = list(zip([x[0] for x in seqs], [x[1] for x in seqs], executor(tasks)))

        # Two-step classification
        # Having a progress bar is pretty but not necessary
        logger.debug("First Stage Classification: Running")
        fst_stage_results = [self.predictors[0].make_prediction(seq) for seq in seqs]

        logger.debug("First Stage Classification: Completed")
        predictions = []
        to_second_stage = []

        for prediction in fst_stage_results:
            if prediction.cls[0] == "organelle":
                to_second_stage.append(prediction)
            else:
                predictions.append(prediction)

        if to_second_stage:
            tasks = (
                transformed_sequences(
                    record.seq,
                    1,
                    self.predictors[1].transformer,
                    self.params[1]["fragment_len"],
                )
                for record in to_second_stage
            )
            cont_manager = time_context_manager("Second Stage Classification: Calculating sequence representations")
            with cont_manager:
                seqs2 = list(
                    # SIGNIFICANT WASTE OF CYCLES, SHOULD BE AN UNPACK
                    zip(
                        [record.desc for record in to_second_stage],
                        [record.seq for record in to_second_stage],
                        executor(tasks),
                    )
                )

            # Note: Having a progress bar is pretty but not necessary
            logger.debug("Second Stage Classification: Running")
            # NOTE: REPLACE WITH A LOGGER WRAPPER AS THIS PATTERN IS USED TWICE?
            snd_stage_results = [self.predictors[1].make_prediction(seq) for seq in seqs2]
            logger.debug("Second Stage Classification: Completed")

            for fst, snd in zip(to_second_stage, snd_stage_results):
                self.validate_first_and_second(fst, snd)
                predictions.append(
                    SingleResult(
                        desc=fst.desc,
                        seq=fst.seq,
                        cls=[fst.cls[0], snd.cls[1]],
                        probs=[fst.probs[0], snd.probs[1]],
                    )
                )

        return predictions

    def validate_first_and_second(self, fst, snd):
        """
        Validate that the HEADERS and SEQUENCES are the same for the first and
        second stage predictions.
        """
        if fst.desc != snd.desc:
            raise ValueError("Headers not the same")
        if fst.seq != snd.seq:
            raise ValueError("Sequences not the same")
